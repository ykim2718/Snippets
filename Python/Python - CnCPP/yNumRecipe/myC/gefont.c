static
int myGetTextStrokeLineCount( string )
   char *string;
{
   GESTROKEFONT font;
   char *p;
   int i,j;

   j=0;
   p=string;
   while (*p) {
      if ((unsigned int)*p>=noof(STROKEFONT)) *p=' ';
      i=0;
      while ((font.whole.word=STROKEFONT[(unsigned int)*p][i++])
         !=0xffff)
         j++;
      p++;
   }
   return j;
}

static
int myGetTextStrokeLines( string,lineuls,total )
   char *string;
   GELINEUL *lineuls;
   int total;
{
   GESTROKEFONT font;
   char *p;
   int charSpace,index,i,scale;
   unsigned long x,xx;

   scale=1000; /* font scaling to 100 */
   charSpace=(int)(scale>>1);
   p=string;
   index=x=0;
   while (*p) {
      if ((unsigned int)*p>=noof(STROKEFONT)) *p=' ';
      i=xx=0;
      while ((font.whole.word=STROKEFONT[(unsigned int)*p][i++])
         !=0xffff) {
         lineuls[index].x1=(font.part.col1  )*scale/7+x;
         lineuls[index].y1=(7-font.part.row1)*scale/7;
         lineuls[index].x2=(font.part.col2  )*scale/7+x;
         lineuls[index].y2=(7-font.part.row2)*scale/7;
         if (lineuls[index].x1>xx) xx=lineuls[index].x1;
         else if (lineuls[index].x2>xx) xx=lineuls[index].x2;
         index++;
         if (index>total)
            return FALSE;
      }
      x= (*p==' ') ? x+scale/2 : xx+charSpace;
      p++;
   }
   return total==index ? TRUE:FALSE;
}

int myDrawTextStroke( myDisplay,x,y,str )
   MYDISPLAY *myDisplay;
   int x,y;
   char *str;
{
   int total,i;
   unsigned long xMax,yMax;
   GELINEUL *lineuls;
   double xo,yo,x1,y1,x2,y2;
   double correctionFactor;

   total=myGetTextStrokeLineCount(str);
   if (!total)
      return FALSE;
   lineuls=salloc(GELINEUL,total);

   if (!myGetTextStrokeLines(str,lineuls,total)) {
      free(lineuls);
      return FALSE;
   }
   xMax=yMax=0;
   for (i=0;i<total;i++) {
      xMax=MAX(lineuls[i].x1,xMax);
      xMax=MAX(lineuls[i].x2,xMax);
      yMax=MAX(lineuls[i].y1,yMax);
      yMax=MAX(lineuls[i].y2,yMax);
   }
   if (myStrokeTextFormat&GE_AlignRight)         xo=(double)xMax;
   else if (myStrokeTextFormat&GE_AlignHCenter)  xo=(double)(xMax>>1);
   else                                       xo=0.0;
   if (myStrokeTextFormat&GE_AlignTop)           yo=(double)yMax;
   else if (myStrokeTextFormat&GE_AlignVCenter)  yo=(double)(yMax>>1);
   else if (myStrokeTextFormat&GE_AlignBaseline) yo=yMax/2.0;
   else                                       yo=0.0;
   /**/
   SaveXMatrix2D();
   /**/
   {
   double **mtx;
   mtx=dmatrix(1,3,1,3);  
   SetXMatrix2DDefault(mtx);
   SetXMatrix2D(mtx,myGEFontMatrix2D.m11,myGEFontMatrix2D.m12,
                    myGEFontMatrix2D.m21,myGEFontMatrix2D.m22,
                    myGEFontMatrix2D.m31,myGEFontMatrix2D.m32);
   ComXMatrix2DAdobe(myGEXMatrix2D,mtx);
   free_dmatrix(mtx,1,3,1,3);
   }
   myGEXMatrix2D[3][1]=x;
   myGEXMatrix2D[3][2]=y;
   correctionFactor=myDisplay->metricScale*0.5; /* stupid 0.5 ! */
   {
   GELINE *lines;
   lines=salloc(GELINE,total);
   for (i=0;i<total;i++) {
      x1=(-xo+(double)lineuls[i].x1)*correctionFactor;
      y1=(-yo+(double)lineuls[i].y1)*correctionFactor;
      x2=(-xo+(double)lineuls[i].x2)*correctionFactor;
      y2=(-yo+(double)lineuls[i].y2)*correctionFactor;
      xform_it(&x1,&y1,&x2,&y2);
      lines[i].x1=(int)x1;
      lines[i].y1=(int)y1;
      lines[i].x2=(int)x2;
      lines[i].y2=(int)y2;
   }
   GEDrawTextLine(myDisplay,lines,total);
   free(lines);
   }
   free(lineuls);
   /**/
   RestoreXMatrix2D();
   /**/
   return TRUE;
}

