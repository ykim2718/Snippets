int GetStrokeSymbolPoints( nCode,xPoints,yPoints,nTotal ) /* 1000 scale */
   int nCode;
   int *xPoints,*yPoints; /* [0..(nTotal-1)] */
   int nTotal;
{
   int nIndex;
   PLTSTROKESYMB symb;

   if (nCode>STROKESYMB_TOTAL) return 0;
   for (nIndex=0;
        (symb.whole.obj=STROKESYMB_TABLE[nCode][nIndex])!=0xff && nIndex<nTotal;
        nIndex++) {
      xPoints[nIndex]=(int)(symb.part.row*1000/16);
      yPoints[nIndex]=(int)(symb.part.col*1000/16);
   }
   return nIndex;
}

